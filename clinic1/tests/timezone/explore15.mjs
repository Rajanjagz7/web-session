import { chromium } from '@playwright/test';
const b = await chromium.launch({ headless: false });
const c = await b.newContext({ viewport: { width: 1440, height: 1000 }, storageState: 'playwright/.auth/tz-user.json' });
const p = await c.newPage();
const o = 'https://sunrise-family-medical.dev.clinic1.ai';
await p.goto(o + '/schedule/settings');
await p.waitForTimeout(5000);
await p.getByRole('combobox').first().click();
await p.getByRole('option', { name: /BRISBANE/i }).click();
await p.waitForTimeout(4000);
await p.getByRole('button', { name: /Add Override/i }).click();
await p.waitForTimeout(2000);
const dlg = p.locator('[role=dialog]').first();
console.log('inputs:', await dlg.locator('input').evaluateAll(l => l.map(i => [i.type, i.name, i.placeholder, i.getAttribute('aria-label'), i.id, i.readOnly])));
await dlg.locator('input').first().click({ force: true });
await p.waitForTimeout(1500);
await p.screenshot({ path: 'test-results/walk/wizard-picker.png' });
const pop = p.locator('[role=dialog], [role=listbox], .MuiPickersPopper-root, .MuiPopper-root');
console.log('popups:', await pop.count());
console.log('picker text:', (await p.locator('body').innerText()).split('\n').filter(Boolean).slice(-40).join(' | '));
await b.close();
