/** Generates docs/traceability-matrix.md from src/notes.ts and the spec files. Run: npm run matrix */
import fs from 'node:fs';
import path from 'node:path';
import { NOTES, type Note } from '../src/notes';

const root = path.resolve(__dirname, '..');
const specDir = path.join(root, 'src', 'specs');
const re = /\b(live|fixme|manual)\(\s*'([A-Z]{3}-\d{2}[a-z]?)'(?:,\s*'([^']*)')?/g;
const where = new Map<string, { file: string; titles: string[] }>();

for (const file of fs.readdirSync(specDir).filter((f) => f.endsWith('.spec.ts'))) {
  const text = fs.readFileSync(path.join(specDir, file), 'utf8');
  for (const m of text.matchAll(re)) {
    const id = m[2] ?? '';
    const entry = where.get(id) ?? { file, titles: [] };
    if (m[3]) entry.titles.push(m[3]);
    where.set(id, entry);
  }
}

const esc = (s: string): string => s.replace(/\|/g, '\\|');
const status = (n: Note): string => (n.kind === 'live' ? 'LIVE test' : n.kind === 'fixme' ? 'test.fixme' : 'MANUAL (test.fixme)');

const lines: string[] = [];
lines.push('# Traceability matrix: FieldR release notes (Production, 6 October 2026)');
lines.push('');
lines.push('Generated by `npm run matrix` from `src/notes.ts` and `src/specs/`. Edit `src/notes.ts`, not this file.');
lines.push('`npm run trace` fails when a bullet has no test of its declared kind.');
lines.push('');
const k = { live: 0, fixme: 0, manual: 0 };
for (const n of NOTES) k[n.kind]++;
lines.push(`**${NOTES.length} bullets:** ${k.live} live, ${k.fixme} fixme (prerequisite named), ${k.manual} manual.`);
lines.push('');
lines.push('| ID | Area | Persona | Release-note bullet | Coverage | Spec file | Test / reason |');
lines.push('| --- | --- | --- | --- | --- | --- | --- |');
for (const n of NOTES) {
  const w = where.get(n.id);
  const detail = n.kind === 'live' ? (w?.titles.join('; ') ?? '') : (n.reason ?? '');
  lines.push(`| ${n.id} | @${n.area} | ${n.persona} | ${esc(n.text)} | ${status(n)} | ${w ? w.file : 'MISSING'} | ${esc(detail)} |`);
}
lines.push('');
lines.push('## Negative and permission tests (first-class)');
lines.push('');
lines.push('| ID | Affordance | Persona that must NOT have it | Checks |');
lines.push('| --- | --- | --- | --- |');
lines.push('| QUO-02 | cost / margin / markup columns | no-cost-viewer | hidden in UI; absent from the customer quote PDF; "Show to Customer" locked off for cost-viewer |');
lines.push('| BUD-03 | budget sell/cost prices | no-cost-viewer | hidden in UI; cost fields absent from the budget API response |');
lines.push('| ROL-01 | New Role entry points | no-permission | hidden in Create menu and palette; roles API returns 403 |');
lines.push('| CUS-02 | Create Job button | no-permission; any user for an inactive customer | hidden |');
lines.push('| LIA-01 | Log In As | no-permission | not offered |');
lines.push('| SEC-01 / SEC-02 | staff / customer invite actions | no-permission | invite button hidden; list, send, resend, cancel return 401/403 |');
lines.push('| SEC-06 / SEC-07 | company rename, other customers\' time logs | portal-customer | rename refused and unchanged; other job returns 403/404 |');
lines.push('');
lines.push('## Environment-dependent items');
lines.push('');
lines.push('- Wall-clock: PLT-02 (manual), DTM-01 (uses `page.clock`).');
lines.push('- App Store / mobile and real payments: IOS-01..03 (manual), SUB-01..03, SBS-01, PUR-01..03, PLT-04 (billing sandbox needed).');
lines.push('- Expected values the notes do not state are `.env` one-line fills: see `.env.example` (EXPECTED_*, FIXTURE_*, PORTAL_*).');

fs.mkdirSync(path.join(root, 'docs'), { recursive: true });
fs.writeFileSync(path.join(root, 'docs', 'traceability-matrix.md'), lines.join('\n') + '\n');
console.log(`wrote docs/traceability-matrix.md (${NOTES.length} rows)`);
